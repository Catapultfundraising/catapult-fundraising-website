// Local only. Every autosave/submission request is intercepted in memory.
const { chromium } = require("playwright");
const assert = require("node:assert/strict"), fs = require("node:fs");
(async () => {
  const out = "/workspace/csnf-proof-v2"; fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || "/opt/viktor-playwright-browsers/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell", headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, extraHTTPHeaders: { "x-forwarded-proto": "https" } });
  await context.addInitScript(() => {
    localStorage.setItem("catapult_cookie_consent", "necessary");
    window.__surveyKeepalive = [];
    const send = window.fetch.bind(window);
    window.fetch = (url, options) => {
      if (String(url).includes("/api/csnf-survey")) window.__surveyKeepalive.push(Boolean(options?.keepalive));
      return send(url, options);
    };
  });
  await context.route("**/*", route => new URL(route.request().url()).hostname === "localhost" ? route.continue() : route.abort());
  const page = await context.newPage(), errors = [], requests = [];
  page.on("pageerror", e => errors.push(e.message));
  let draftFailure = true, finalAttempt = 0;
  await page.route("**/api/csnf-survey", async route => {
    const b = JSON.parse(route.request().postData()); requests.push(b);
    const status = b.status === "draft" ? draftFailure ? 503 : 200 : ++finalAttempt === 1 ? 400 : finalAttempt === 2 ? 503 : 200;
    if (b.status === "draft") draftFailure = false;
    return route.fulfill({ status, contentType: "application/json", body: JSON.stringify(status !== 200 ? { error: "Fixture save failure" } : { ok: true, id: b.id, status: b.status, revision: b.revision, updatedAt: new Date().toISOString() }) });
  });
  await page.goto("http://localhost:3100/csnf-survey", { waitUntil: "domcontentloaded" });
  await page.getByRole("heading", { name: "CSNF Survey", exact: true }).waitFor();
  await page.addStyleTag({ content: "nextjs-portal{display:none!important}" });
  assert.equal(await page.locator('input[type="radio"]').count(), 34);
  assert.equal(await page.locator('input[type="checkbox"]').count(), 7);
  assert.equal(await page.locator("textarea").count(), 10);
  assert.equal(await page.locator("legend").count(), 0, "question text is inside white cards, not border legends");
  const logo = await page.locator("header img").boundingBox(), column = await page.locator("#case-summary").boundingBox();
  assert.ok(Math.abs(logo.x - column.x) < 2, "logo aligns with paragraph column");
  const q4 = page.locator('fieldset[aria-labelledby="question-q4"]');
  const card = await q4.boundingBox(), heading = await page.locator("#question-q4").boundingBox();
  assert.ok(heading.y > card.y + 10 && heading.x > card.x + 10, "question heading fully inside card");
  assert.ok((await page.locator("#survey-firstName").getAttribute("required")) !== null);
  assert.equal(await page.locator("#survey-telephone").getAttribute("required"), null);
  assert.ok((await page.locator("#autosave-disclosure").innerText()).includes("including unfinished surveys"));
  await page.screenshot({ path: `${out}/survey-v2-desktop-top.png` });
  await page.locator('section[aria-labelledby="your-details"]').evaluate(el => el.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: `${out}/survey-v2-desktop-identity.png` });
  await page.locator("#survey-firstName").fill("Sample");
  await page.locator('input[name="q1"][value="Good"]').check();
  await page.evaluate(() => window.dispatchEvent(new Event("pagehide")));
  assert.equal(requests.length, 0, "no save with only first name, including page exit");
  const firstSave = page.waitForResponse(r => r.url().endsWith("/api/csnf-survey"));
  await page.locator("#survey-lastName").fill("Reviewer-李");
  await firstSave;
  await page.getByRole("status").filter({ hasText: "not confirmed saved" }).waitFor();
  assert.ok(await page.locator('input[name="q1"][value="Average"]').isEnabled(), "continued editing after failed draft save");
  await page.getByRole("button", { name: "Retry saving", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Saved automatically" }).waitFor();
  await page.locator('input[name="q1"][value="Average"]').check();
  const editedSave = page.waitForResponse(r => r.url().endsWith("/api/csnf-survey") && r.request().postDataJSON().telephone === "+44 20 1234 5678 ext. 9");
  await page.locator("#survey-telephone").fill("+44 20 1234 5678 ext. 9");
  await editedSave;
  await page.getByRole("status").filter({ hasText: "Saved automatically" }).waitFor();
  assert.ok(requests.length >= 3);
  assert.ok(JSON.stringify(requests[0]) === JSON.stringify(requests[1]), "failed revision retried with exact same payload/capability");
  assert.ok(requests[2].revision > requests[1].revision); assert.equal(requests.at(-1).answers.q1, "Average");
  const beforeClear = requests.length;
  await page.locator("#survey-firstName").fill("");
  await page.getByRole("status").filter({ hasText: "First and last name are needed" }).waitFor();
  await page.evaluate(() => window.dispatchEvent(new Event("pagehide")));
  assert.equal(requests.length, beforeClear, "clearing names does not send invalid data or erase saved draft");
  await page.locator("#survey-firstName").fill("Sample");
  await page.locator('input[name="q2"][value="Yes"]').check();
  const exitSave = page.waitForResponse(r => r.url().endsWith("/api/csnf-survey"));
  await page.evaluate(() => window.dispatchEvent(new Event("pagehide")));
  await exitSave;
  assert.equal(requests.at(-1).status, "draft"); assert.equal(requests.at(-1).answers.q2, "Yes");
  assert.ok((await page.evaluate(() => window.__surveyKeepalive)).includes(true), "pagehide flush uses keepalive before debounce");
  await page.getByRole("status").filter({ hasText: "Saved automatically" }).waitFor();
  await page.locator("#question-q4").scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${out}/survey-v2-desktop-questions.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `${out}/survey-v2-mobile-top.png` });
  await page.locator('section[aria-labelledby="your-details"]').evaluate(el => el.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: `${out}/survey-v2-mobile-identity.png` });
  await page.locator("#question-q4").scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${out}/survey-v2-mobile-questions.png` });
  const finalSave = page.waitForResponse(r => r.url().endsWith("/api/csnf-survey") && r.request().postDataJSON().status === "submitted");
  await page.getByRole("button", { name: "Submit survey", exact: true }).click(); await finalSave;
  await page.getByRole("button", { name: "Submit survey", exact: true }).waitFor();
  assert.ok(await page.locator("#survey-telephone").isEnabled(), "known final400 permits correction");
  const correction = page.waitForResponse(r => r.url().endsWith("/api/csnf-survey") && r.request().postDataJSON().telephone === "+44 20 9999 0000");
  await page.locator("#survey-telephone").fill("+44 20 9999 0000"); await correction;
  await page.getByRole("status").filter({ hasText: "Saved automatically" }).waitFor();
  await page.getByRole("button", { name: "Submit survey", exact: true }).click();
  await page.getByRole("button", { name: "Retry submission", exact: true }).waitFor();
  assert.ok(await page.locator("#survey-firstName").isDisabled(), "ambiguous final state freezes edits");
  await page.getByRole("button", { name: "Retry submission", exact: true }).click();
  await page.getByRole("heading", { name: "Thank you for sharing your perspective.", exact: true }).waitFor();
  const finals = requests.filter(r => r.status === "submitted");
  assert.equal(finals.length, 3);
  assert.ok(JSON.stringify(finals[1]) === JSON.stringify(finals[2]), "ambiguous terminal retry has one immutable final revision/payload");
  assert.equal(finals[0].revision, 1000001);
  const doneCount = requests.length; await page.evaluate(() => window.dispatchEvent(new Event("pagehide")));
  assert.equal(requests.length, doneCount, "no autosaves after confirmed submission");
  await page.screenshot({ path: `${out}/survey-v2-success-mobile.png` });
  assert.equal(errors.length, 0, "no browser JavaScript errors");
  await browser.close();
  console.log("PASS v2 browser: logo alignment/in-card questions, required names/optional phone, partial autosave without Submit, failed save/edit/retry, cleared-name status, keepalive exit flush, final frozen retry/unique sentinel, desktop/mobile no overflow or JS errors.");
})().catch(e => { console.error(e); process.exit(1); });
