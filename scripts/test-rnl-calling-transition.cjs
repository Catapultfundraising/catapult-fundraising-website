const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = p => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const page = read('app/rnl-calling-program-alternative/page.tsx');
const route = '/rnl-calling-program-alternative';
const umgc = page.match(/<section aria-labelledby="umgc-heading"[\s\S]*?<\/section>/)?.[0];
const sacramento = page.match(/<section aria-labelledby="sacramento-heading"[\s\S]*?<\/section>/)?.[0];
assert(umgc && sacramento, 'Universities must have independently labeled sections');
assert(umgc.includes('University of Maryland Global Campus') && umgc.includes('$238,754') && umgc.includes('1,107'));
assert(!umgc.includes('TestimonialQuote') && !umgc.includes('sacramento'));
assert(sacramento.includes('Sacramento State University') && sacramento.includes('quote: [SACRAMENTO_EXCERPT]'));
assert(page.includes('t.id === "erica-kobbe"'), 'Quote attribution must use canonical Sacramento testimonial');
assert(read('lib/testimonials.ts').includes('Their callers are exceptionally well-trained, authentic, and a true extension of our advancement team.'));
assert(page.includes('title: { absolute: TITLE }') && page.includes('alternates: { canonical: PATH }'));
assert(page.includes('FAQS.map((f)') && page.includes('FAQS.map((faq)'), 'Schema and visible answers share one source');
assert(page.includes('https://go.catapultfr.com/meetings/anthonya'));
assert(page.includes('not affiliated with or endorsed by Ruffalo Noel Levitz'));
assert(!/RNL.{0,40}(ending|closing|discontinuing|shutting)/i.test(page));
assert(!/\u2014/.test(page));
for(const p of ['app/services/telefundraising/page.tsx','app/blog/is-the-phonathon-dead/page.tsx']) assert.equal(read(p).split(`href="${route}"`).length-1,1,`${p} must link once to the transition page`);
const sitemap = read('app/sitemap.ts');
assert(sitemap.includes(`"${route}": "2026-11-17"`));
assert.equal(sitemap.split(`    "${route}",`).length-1,1);
assert(read('lib/lead-attribution.ts').includes(`pathname === "${route}"`));
console.log('PASS: RNL transition copy, independently labeled university proof, attribution, SEO, links and sitemap.');
